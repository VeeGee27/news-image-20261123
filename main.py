#!/usr/bin/env python3
"""Copy entry.png to the current directory, byte-verified.

Usage: python3 main.py
The entry image is generated by draw.py and copied here unchanged.
Standard library only.
"""
import hashlib
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "entry.png")
DST = os.path.join(os.getcwd(), "entry.png")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    if not os.path.exists(SRC):
        print("error: entry.png not found next to main.py", file=sys.stderr)
        return 1
    shutil.copyfile(SRC, DST)
    if sha256(SRC) != sha256(DST):
        print("error: byte verification failed", file=sys.stderr)
        return 1
    print("copied entry.png (%d bytes, sha256 %s)"
          % (os.path.getsize(DST), sha256(DST)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
